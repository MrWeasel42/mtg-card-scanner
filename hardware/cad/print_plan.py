"""Writes ../PRINT_PLAN.md: every printed part, how many in each stage, size and print notes.
Stage A = 3-bin raw-card test machine, B = the other 6 bins, C = sleeved towers."""
import os
from sorter import PRINTED, STAGES

DONE = {"fit_coupon": "printed", "motor_standoff": "printed (plate 1)", "gate_plate": "printed (plate 1)"}
rows = {"A": [], "B": [], "C": []}
for name, (fn, mat, note) in PRINTED.items():
    bb = fn().val().BoundingBox()
    size = f"{bb.xlen:.0f} x {bb.ylen:.0f} x {bb.zlen:.0f} mm ({bb.xlen / 25.4:.1f} x {bb.ylen / 25.4:.1f} x {bb.zlen / 25.4:.1f} in)"
    for st, q in zip("ABC", STAGES[name]):
        if q:
            rows[st].append(f"| `{name}.stl` | {q} | {mat} | {size} | {DONE.get(name, '') if st == 'A' else ''} | {note} |")
title = {"A": "Stage A: the 3-bin test machine, raw cards (print and build this first)",
         "B": "Stage B: bins 3-8 (print while testing A; they go in between bin module 2 and the end module)",
         "C": "Stage C: sleeved towers"}
out = ["# Print plan", "", "Generated by `cad/print_plan.py` from the CAD. Files are in `stl/` (and `step/`).",
       "Every part is the final 9-bin design: stage A is just the first part of it. Going from A to B: unbolt the end",
       "module from bin module 2, bolt modules 3-8 in, bolt the end module back on, swap the 1220 mm belts for the",
       "2684 mm welded ones and add the fins (22 per belt). Nothing printed in A is thrown away.", ""]
for st in "ABC":
    out += [f"## {title[st]}", "", "| File | Qty | Material | Size | Status | Notes |", "|---|---|---|---|---|---|"] + rows[st] + [""]
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "PRINT_PLAN.md"), "w").write("\n".join(out) + "\n")
print("ok")
